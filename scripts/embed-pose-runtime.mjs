/**
 * Embeds runtime/pose-runtime.js into src (and lib) as a small CommonJS module.
 * Light SDK ships only this ~50 KB page runtime — TF.js + model stay remote.
 *
 * Usage: node scripts/embed-pose-runtime.mjs
 */
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const runtimePath = join(root, 'runtime/pose-runtime.js');
if (!existsSync(runtimePath)) {
  console.error(`Missing ${runtimePath}`);
  process.exit(1);
}

const runtimeJs = readFileSync(runtimePath, 'utf8').replace(/<\/script/gi, '<\\/script');
const version = `online-${createHash('sha256').update(runtimeJs, 'utf8').digest('hex').slice(0, 8)}`;

const js = [
  '/** AUTO-GENERATED by scripts/embed-pose-runtime.mjs — do not edit. */',
  `'use strict';`,
  `exports.POSE_RUNTIME_VERSION = ${JSON.stringify(version)};`,
  `exports.POSE_RUNTIME_JS = ${JSON.stringify(runtimeJs)};`,
  '',
].join('\n');

const dts = [
  '/** AUTO-GENERATED by scripts/embed-pose-runtime.mjs — do not edit. */',
  'export declare const POSE_RUNTIME_VERSION: string;',
  'export declare const POSE_RUNTIME_JS: string;',
  '',
].join('\n');

const webviewDir = join(root, 'src/backends/webview');
mkdirSync(webviewDir, { recursive: true });
writeFileSync(join(webviewDir, 'poseRuntimeSource.js'), js);
writeFileSync(join(webviewDir, 'poseRuntimeSource.d.ts'), dts);

const libWebviewDir = join(root, 'lib/backends/webview');
mkdirSync(libWebviewDir, { recursive: true });
copyFileSync(join(webviewDir, 'poseRuntimeSource.js'), join(libWebviewDir, 'poseRuntimeSource.js'));
copyFileSync(join(webviewDir, 'poseRuntimeSource.d.ts'), join(libWebviewDir, 'poseRuntimeSource.d.ts'));

console.log(`poseRuntimeSource → ${version} (${Buffer.byteLength(runtimeJs, 'utf8')} bytes)`);
